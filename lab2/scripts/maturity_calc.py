#!/usr/bin/env python3

domains = [
    ("Керування доступом та ідентифікація (IAM)", 4, 5, "Впроваджено RBAC та MFA для адмінів; потрібно поширити MFA на викладачів."),
    ("Мережева безпека та захист периметра", 4, 5, "Налаштовано UFW та сегментацію DMZ; рекомендовано додати IDS/IPS."),
    ("Криптографічний захист даних", 4, 5, "Використовується HTTPS/mTLS та шифрування БД; автоматизувати ротацію ключів."),
    ("Журналювання та моніторинг подій", 3, 4, "Працює auditd; варто підключити централізовану SIEM-систему з алертами."),
    ("Управління вразливостями та безпека коду", 3, 4, "Проведено моделювання загроз PyTM; додати автоматичний SAST у CI/CD."),
    ("Безперервність роботи та резервне копіювання", 3, 4, "Резервні копії створюються; затвердити графік регулярного тестування відновлення.")
]

levels = {
    1: "Початковий (Initial)",
    2: "Повторюваний (Repeatable)",
    3: "Визначений (Defined)",
    4: "Керований (Managed)",
    5: "Оптимізований (Optimized)"
}

avg_current = sum(d[1] for d in domains) / len(domains)
avg_target = sum(d[2] for d in domains) / len(domains)

print("=== ОЦІНКА ЗРІЛОСТІ СИСТЕМИ ІНФОРМАЦІЙНОЇ БЕЗПЕКИ (5-БАЛЬНА ШКАЛА) ===\n")
print(f"{'Домен безпеки':<44} | {'Поточний':<8} | {'Цільовий':<8}")
print("-" * 68)
for name, cur, trg, _ in domains:
    print(f"{name:<44} | {cur}/5      | {trg}/5")

print("-" * 68)
print(f"Середній поточний рівень зрілості: {avg_current:.2f} / 5.00 ({levels[round(avg_current)]})")
print(f"Цільовий рівень після рекомендацій: {avg_target:.2f} / 5.00 ({levels[round(avg_target)]})")

md = [
    "# Звіт первинної оцінки зрілості інформаційної безпеки\n",
    "Оцінювання виконано за 5-бальною шкалою зрілості процесів (від 1 — *Початковий* до 5 — *Оптимізований*).\n",
    "| Домен безпеки | Поточний бал | Цільовий бал | Рекомендації щодо посилення контролю |",
    "| :--- | :---: | :---: | :--- |"
]
for name, cur, trg, rec in domains:
    md.append(f"| {name} | {cur}/5 | {trg}/5 | {rec} |")

md.append(f"\n**Загальний поточний показник зрілості:** `{avg_current:.2f} / 5.00` — рівень **{levels[round(avg_current)]}**.")
md.append(f"**Прогнозований показник після виконання рекомендацій:** `{avg_target:.2f} / 5.00` — рівень **{levels[round(avg_target)]}**.")

with open("lab2/assessment/Maturity_Assessment.md", "w", encoding="utf-8") as f:
    f.write("\n".join(md) + "\n")
